export function getPaymentLang(url: URL, cookieLang?: string): PaymentLang {
  const fromQuery = url.searchParams.get("lang");
  if (fromQuery === "en" || fromQuery === "ar") return fromQuery;
  if (cookieLang === "en" || cookieLang === "ar") return cookieLang as PaymentLang;
  return "ar";
}

export function t(lang: PaymentLang) {
  return PAYMENT_TRANSLATIONS[lang];
}
